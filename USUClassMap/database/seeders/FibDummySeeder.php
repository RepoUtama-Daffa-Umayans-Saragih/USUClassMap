    /**
     * Helper untuk mendapatkan atau membuat data Dosen dengan email dinamis @usu.ac.id.
     */
    private function getOrCreateLecturer(string $name): Lecturer
    {
        $cleanName = trim($name);

        $lecturer = Lecturer::where('name', $cleanName)->first();
        if ($lecturer) {
            return $lecturer;
        }

        // Generate NIP & Email unik berbasis slug nama dosen
        $slug = Str::slug(preg_replace('/[^a-zA-Z0-9\s]/', '', $cleanName));
        if (empty($slug)) {
            $slug = 'dosen.fib.' . uniqid();
        }
        $pseudoNip = '19' . str_pad((string)abs(crc32($cleanName) % 10000000000), 10, '0', STR_PAD_LEFT);
        $email = $slug . '@usu.ac.id';

        return Lecturer::firstOrCreate(
            ['name' => $cleanName],
            [
                'nip' => $pseudoNip,
                'email' => $email,
                'phone' => '0812' . rand(10000000, 99999999),
            ]
        );
    }
